# src/agent/agent.py

import json

from src.ai.llm_client import ask_llm

from src.agent.tools import (
    execute_tool
)

from src.agent.tool_schema import (
    TOOLS
)

from src.logger import logger


# =========================================================
# Agent 参数
# =========================================================

# Agent 最多运行多少轮
#
# 例如：
#
# 第1轮：搜索
# 第2轮：读取正文
# 第3轮：回答
#
# 如果连续5轮都没有结束，
# 就强制结束，防止 Agent 无限循环。
MAX_TOOL_ROUNDS = 5


# 单轮工具调用的建议上限
#
# 注意：
# 这里只用于监控和日志，
# 不直接截断 tool_calls。
#
# 原因：
# 如果模型一次返回4个 tool call，
# 我们直接只执行前3个，
# 可能导致 assistant tool_calls 和
# tool result 数量不匹配。
MAX_TOOLS_PER_ROUND = 3


def run_agent(question):

    # =====================================================
    # 记录用户问题
    # =====================================================

    logger.info(
        f"用户问题: {question}"
    )


    # =====================================================
    # 初始化 messages
    # =====================================================

    messages = [

        {
            "role": "system",

            "content": """
你是一个专业的AI科技新闻研究助手。

你的任务是：
根据用户问题，从新闻数据库和知识库中获取必要信息，并给出准确、简洁的中文回答。


==============================
一、工具选择原则
==============================

1. 用户询问“最近有哪些新闻”“最新新闻”：

   使用 search_latest_news。

   例如：
   - 最近有哪些 AI 新闻？
   - 最新有哪些 AI 新闻？


2. 用户明确指定新闻分类：

   使用 search_category_news。

   例如：
   - 最近有哪些机器人新闻？
   - 最近有哪些大模型新闻？
   - 最近有哪些开源新闻？

   如果分类工具已经能够回答问题，
   通常不要再调用 search_latest_news 或 search_keyword。


3. 用户明确指定新闻来源：

   使用 search_source_news。

   例如：
   - Anthropic 最近有什么新闻？
   - DeepMind 最近有什么动态？

   如果来源工具已经能够回答问题，
   通常不要再调用其他搜索工具。


4. 用户询问明确的模型、产品或关键词：

   使用 search_keyword。

   例如：
   - Gemini 最近有什么新闻？
   - Claude 最近有什么进展？
   - Gemma 最近有什么消息？


5. 用户询问原因、意义、技术细节、背景、影响或趋势：

   优先使用 search_knowledge。

   例如：
   - 为什么 Gemini Robotics 2 很重要？
   - Gemini Robotics 2 如何实现全身控制？
   - 这项技术有什么意义？
   - AI Agent 最近的发展趋势是什么？


6. 用户要求深入分析某一篇具体新闻：

   先找到目标新闻，
   然后根据需要调用 get_news_detail
   读取完整正文。


7. 用户要求比较两个或多个对象：

   分别检索相关对象，
   获取必要的信息后再进行比较。


==============================
二、避免重复调用
==============================

1. 如果一个工具已经返回足够的信息，
   不要为了保险再次调用其他工具。


2. 不要对同一个目标重复搜索。


3. search_category_news 已经能够回答某个分类的新闻列表时：

   通常不要再调用：
   - search_latest_news
   - search_keyword


4. search_source_news 已经能够回答某个来源的新闻列表时：

   通常不要再调用其他搜索工具。


5. search_keyword 已经找到明确目标新闻，
   如果用户只是想知道基本信息：

   不要立即调用 get_news_detail。


6. 只有以下情况才继续调用其他工具：

   - 当前信息不足
   - 用户要求深入分析
   - 用户要求解释原因
   - 用户要求比较多个对象
   - 用户要求查看新闻正文
   - 用户明确要求更多细节


==============================
三、工具调用策略
==============================

1. 优先使用最少数量的工具完成任务。


2. 工具返回的信息已经足够时，
   立即停止工具调用并回答。


3. 不要为了让回答看起来更长而继续检索。


4. 如果第一次检索结果已经能够解决问题，
   不需要再次搜索相同内容。


5. 如果需要多步任务，
   根据当前工具返回结果决定下一步。


6. 不要固定执行某个工具组合。


7. Agent应该根据用户问题自主决定：
   - 查什么
   - 是否继续查
   - 是否读取全文
   - 什么时候停止


==============================
四、RAG使用原则
==============================

当用户询问：

- 为什么
- 如何实现
- 有什么意义
- 技术细节
- 背景
- 原因
- 影响
- 趋势
- 深入分析

优先使用 search_knowledge。

search_knowledge 会从新闻知识库中进行 Hybrid Retrieval，
结合：

- SQLite关键词检索
- Chroma向量检索

获取与用户问题相关的知识。


==============================
五、完整正文原则
==============================

当用户要求深入分析某篇具体新闻时：

第一步：
找到新闻。

第二步：
获取新闻ID。

第三步：
调用 get_news_detail。

第四步：
读取完整正文。

第五步：
根据正文进行分析。


不要对所有搜索结果都读取完整正文。


==============================
六、停止条件
==============================

满足以下条件之一时，直接回答：

1. 已经获得足够信息。

2. 用户的问题已经被工具结果充分回答。

3. 没有必要继续调用其他工具。

不要进行无意义的重复检索。


==============================
七、回答原则
==============================

1. 只能根据工具返回的数据回答。


2. 不要编造数据库或知识库中不存在的信息。


3. 如果数据库中没有足够信息：

   明确告诉用户目前的数据有限。


4. 使用中文。


5. 直接回答用户问题。


6. 不要为了显示“智能”而进行多余工具调用。


7. 可以对检索到的信息进行总结、比较和分析，
   但不能凭空加入数据库中没有的信息。
"""
        },

        {
            "role": "user",

            "content": question
        }

    ]


    # =====================================================
    # Agent 循环
    # =====================================================

    for round_number in range(
        MAX_TOOL_ROUNDS
    ):

        current_round = (
            round_number + 1
        )


        logger.info(
            f"Agent第 {current_round} 轮思考"
        )


        # =================================================
        # 调用 LLM
        # =================================================

        try:

            response = ask_llm(

                messages=messages,

                tools=TOOLS

            )

        except Exception as e:

            logger.exception(
                "LLM调用失败"
            )

            return (
                "调用大模型失败，请稍后重试。"
            )


        # =================================================
        # 获取 assistant message
        # =================================================

        message = (
            response
            .choices[0]
            .message
        )


        # =================================================
        # 没有工具调用
        #
        # 说明 Agent 已经决定直接回答
        # =================================================

        if not message.tool_calls:

            logger.info(
                "Agent决定直接回答"
            )


            return (
                message.content
                or ""
            )


        # =================================================
        # 保存 assistant 的 tool call 消息
        # =================================================

        messages.append(
            message
        )


        # =================================================
        # 获取本轮工具调用
        # =================================================

        tool_calls = (
            message.tool_calls
        )


        tool_call_count = len(
            tool_calls
        )


        logger.info(
            f"本轮工具调用数量: "
            f"{tool_call_count}"
        )


        # =================================================
        # 工具调用数量监控
        #
        # 注意：
        # 不截断，只记录 warning。
        # =================================================

        if (
            tool_call_count
            > MAX_TOOLS_PER_ROUND
        ):

            logger.warning(
                f"本轮工具调用数量较多: "
                f"{tool_call_count} 个，"
                f"超过建议上限 "
                f"{MAX_TOOLS_PER_ROUND} 个"
            )


        # =================================================
        # 执行工具
        # =================================================

        for tool_call in tool_calls:

            # -------------------------------------------------
            # 工具名称
            # -------------------------------------------------

            tool_name = (
                tool_call
                .function
                .name
            )


            # -------------------------------------------------
            # 工具参数原始字符串
            # -------------------------------------------------

            arguments_text = (
                tool_call
                .function
                .arguments
            )


            logger.info(
                f"模型选择工具: {tool_name}"
            )


            logger.info(
                f"工具参数: {arguments_text}"
            )


            # =================================================
            # 解析工具参数
            # =================================================

            try:

                arguments = json.loads(
                    arguments_text
                )


            except json.JSONDecodeError as e:

                logger.error(
                    f"工具参数解析失败: {e}"
                )


                result = {

                    "error":
                        "工具参数不是合法JSON"

                }


                # -------------------------------------------------
                # 即使参数解析失败，
                # 也必须给这个 tool_call 对应的 tool result
                # -------------------------------------------------

                messages.append(

                    {
                        "role": "tool",

                        "tool_call_id":
                            tool_call.id,

                        "content":
                            json.dumps(

                                result,

                                ensure_ascii=False

                            )
                    }

                )


                continue


            # =================================================
            # 执行工具
            # =================================================

            try:

                result = execute_tool(

                    tool_name,

                    arguments

                )


                logger.info(
                    f"工具执行完成: {tool_name}"
                )


            except Exception as e:

                logger.exception(
                    f"工具执行失败: {tool_name}"
                )


                result = {

                    "error":
                        str(e)

                }


            # =================================================
            # 将工具结果加入 messages
            # =================================================

            messages.append(

                {
                    "role": "tool",

                    "tool_call_id":
                        tool_call.id,

                    "content":
                        json.dumps(

                            result,

                            ensure_ascii=False

                        )
                }

            )


    # =====================================================
    # 达到最大工具调用轮数
    # =====================================================

    logger.warning(
        "Agent达到最大工具调用轮数"
    )


    return (
        "Agent执行步骤过多，"
        "暂时无法完成这个问题。"
    )